use serde::{Deserialize, Serialize};
use std::{
    fs, io,
    path::{Path, PathBuf},
};

#[cfg(target_os = "linux")]
use std::process::Command;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SubvolumeSpec {
    pub name: String,
    pub mount_point: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BtrfsLayout {
    pub partition_dev: PathBuf,
    pub label: String,
    pub subvolumes: Vec<SubvolumeSpec>,
    pub mount_options: String,
}

/// Returns the default Btrfs subvolume layout used by Bifröst on Linux targets.
pub fn default_btrfs_layout(partition_dev: &Path) -> BtrfsLayout {
    BtrfsLayout {
        partition_dev: partition_dev.to_path_buf(),
        label: "BIFROEST_LINUX".to_string(),
        subvolumes: vec![
            SubvolumeSpec {
                name: "@root".to_string(),
                mount_point: "/".to_string(),
            },
            SubvolumeSpec {
                name: "@home".to_string(),
                mount_point: "/home".to_string(),
            },
            SubvolumeSpec {
                name: "@blackbox".to_string(),
                mount_point: "/var/lib/bifrost".to_string(),
            },
            SubvolumeSpec {
                name: "@snapshots".to_string(),
                mount_point: "/.snapshots".to_string(),
            },
        ],
        mount_options: "noatime,compress=zstd:1,space_cache=v2".to_string(),
    }
}

/// Generates an `/etc/fstab` configuration matching the selected target filesystem and partition UUIDs.
pub fn generate_fstab(
    linux_uuid: &str,
    efi_uuid: &str,
    ntfs_uuid: Option<&str>,
    target_fs: &str,
) -> String {
    let mut out = String::from("# /etc/fstab: static file system information generated by Bifroest\n");
    out.push_str("# <file system> <mount point> <type> <options> <dump> <pass>\n\n");

    if target_fs.to_lowercase().contains("btrfs") {
        let layout = default_btrfs_layout(Path::new("/dev/vda4"));
        for sub in &layout.subvolumes {
            out.push_str(&format!(
                "UUID={linux_uuid} {} btrfs {},subvol={} 0 0\n",
                sub.mount_point, layout.mount_options, sub.name
            ));
        }
    } else {
        out.push_str(&format!(
            "UUID={linux_uuid} / ext4 defaults,noatime 0 1\n"
        ));
    }

    out.push_str(&format!(
        "UUID={efi_uuid} /boot/efi vfat umask=0077,shortname=winnt 0 2\n"
    ));

    if let Some(win_uuid) = ntfs_uuid {
        out.push_str(&format!(
            "UUID={win_uuid} /mnt/windows ntfs3 defaults,nofail,uid=1000,gid=1000 0 0\n"
        ));
    }

    out
}

/// Formats/prepares target filesystems (Btrfs subvolumes or Ext4), creates directory mounts, and writes `/etc/fstab`.
pub fn setup_target_filesystems<F>(
    target_root: &Path,
    linux_part: &Path,
    efi_part: &Path,
    target_fs: &str,
    dry_run: bool,
    mut progress_cb: F,
) -> io::Result<String>
where
    F: FnMut(&str, usize, usize),
{
    let is_btrfs = target_fs.to_lowercase().contains("btrfs");
    let total_steps = if is_btrfs { 4 } else { 3 };

    progress_cb(
        &format!(
            "Formatiere {} ({})",
            linux_part.display(),
            if is_btrfs { "Btrfs" } else { "Ext4" }
        ),
        1,
        total_steps,
    );

    #[cfg(target_os = "linux")]
    if !dry_run {
        let layout = default_btrfs_layout(linux_part);
        let lp_str = linux_part.to_string_lossy();
        let efi_str = efi_part.to_string_lossy();
        if is_btrfs {
            run_checked("mkfs.btrfs", &["-f", "-L", &layout.label, &lp_str])?;
            run_checked("mount", &[&lp_str, &target_root.to_string_lossy()])?;
            for sub in &layout.subvolumes {
                let sub_path = target_root.join(&sub.name);
                run_checked("btrfs", &["subvolume", "create", &sub_path.to_string_lossy()])?;
            }
            run_checked("umount", &[&target_root.to_string_lossy()])?;
            let root_opts = format!("{},subvol=@root", layout.mount_options);
            run_checked("mount", &["-o", &root_opts, &lp_str, &target_root.to_string_lossy()])?;
        } else {
            run_checked("mkfs.ext4", &["-F", "-L", "BIFROEST_LINUX", &lp_str])?;
            run_checked("mount", &[&lp_str, &target_root.to_string_lossy()])?;
        }
        let efi_mnt = target_root.join("boot/efi");
        fs::create_dir_all(&efi_mnt)?;
        let _ = Command::new("mount").args([efi_str.as_ref(), &efi_mnt.to_string_lossy()]).output();
    }

    if is_btrfs {
        progress_cb(
            "Lege Btrfs Subvolumes (@root, @home, @blackbox, @snapshots) an...",
            2,
            total_steps,
        );
    }

    let step_dirs = if is_btrfs { 3 } else { 2 };
    progress_cb(
        &format!(
            "Erstelle Mountpoints unter {} (EFI: {})",
            target_root.display(),
            efi_part.display()
        ),
        step_dirs,
        total_steps,
    );

    for rel in [
        "home",
        "var/lib/bifrost",
        ".snapshots",
        "boot/efi",
        "mnt/windows",
        "etc",
    ] {
        fs::create_dir_all(target_root.join(rel))?;
    }

    #[cfg(target_os = "linux")]
    if !dry_run && is_btrfs {
        let layout = default_btrfs_layout(linux_part);
        let lp_str = linux_part.to_string_lossy();
        for sub in layout.subvolumes.iter().filter(|s| s.name != "@root") {
            let mnt_rel = sub.mount_point.trim_start_matches('/');
            let mnt_target = target_root.join(mnt_rel);
            let opts = format!("{},subvol={}", layout.mount_options, sub.name);
            run_checked("mount", &["-o", &opts, &lp_str, &mnt_target.to_string_lossy()])?;
        }
    }

    let linux_uuid = resolve_uuid_or_placeholder(linux_part, "BIFROEST-ROOT-UUID", dry_run);
    let efi_uuid = resolve_uuid_or_placeholder(efi_part, "BIFROEST-EFI-UUID", dry_run);

    progress_cb("Generiere /etc/fstab...", total_steps, total_steps);
    let fstab_content = generate_fstab(&linux_uuid, &efi_uuid, None, target_fs);
    let fstab_path = target_root.join("etc/fstab");
    fs::write(&fstab_path, &fstab_content)?;

    Ok(fstab_content)
}

fn resolve_uuid_or_placeholder(dev: &Path, fallback: &str, _dry_run: bool) -> String {
    #[cfg(target_os = "linux")]
    if !_dry_run {
        if let Ok(out) = Command::new("blkid")
            .args(["-s", "UUID", "-o", "value", &dev.to_string_lossy()])
            .output()
        {
            let uuid = String::from_utf8_lossy(&out.stdout).trim().to_string();
            if !uuid.is_empty() {
                return uuid;
            }
        }
    }
    let _ = dev;
    fallback.to_string()
}

#[cfg(target_os = "linux")]
fn run_checked(bin: &str, args: &[&str]) -> io::Result<()> {
    let out = Command::new(bin).args(args).output()?;
    if !out.status.success() {
        let stderr = String::from_utf8_lossy(&out.stderr);
        return Err(io::Error::new(
            io::ErrorKind::Other,
            format!("{bin} fehlgeschlagen: {stderr}"),
        ));
    }
    Ok(())
}
